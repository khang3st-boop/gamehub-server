-- Game Hub online: bạn bè, phòng đấu realtime, chat trong phòng, điểm xếp hạng online.

-- Kết bạn: một hàng cho mỗi cặp (user_low < user_high theo thứ tự UUID chuỗi) để không trùng chiều.
CREATE TABLE friendships (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low      UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    user_high     UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    requester_id  UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status        VARCHAR(10) NOT NULL,           -- PENDING | ACCEPTED
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    responded_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_friend_pair UNIQUE (user_low, user_high)
);
CREATE INDEX ix_friend_low ON friendships (user_low, status);
CREATE INDEX ix_friend_high ON friendships (user_high, status);

-- Phòng đấu realtime giữa hai người. Đề (config) do SERVER sinh; kết quả do SERVER quyết định.
CREATE TABLE matches (
    id              UUID PRIMARY KEY,
    game            VARCHAR(16)  NOT NULL,         -- rubik | sudoku | puzzle | caro
    mode            VARCHAR(32)  NOT NULL,
    source          VARCHAR(12)  NOT NULL,         -- INVITE | MATCHMAKING
    status          VARCHAR(16)  NOT NULL,         -- WAITING_READY | COUNTDOWN | PLAYING | FINISHED | CANCELLED | ABANDONED
    player_a        UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    player_b        UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    config          VARCHAR(4000) NOT NULL,        -- JSON: scramble / puzzle / ảnh + seed / luật Caro
    a_ready         BOOLEAN      NOT NULL DEFAULT FALSE,
    b_ready         BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    ready_deadline  TIMESTAMP WITH TIME ZONE NOT NULL,
    start_at        TIMESTAMP WITH TIME ZONE,      -- thời điểm bắt đầu tính giờ (sau đếm ngược)
    finished_at     TIMESTAMP WITH TIME ZONE,
    winner_id       UUID,
    end_reason      VARCHAR(16),                   -- SOLVED | CARO_WIN | DRAW | FORFEIT | TIMEOUT | DISCONNECT | READY_TIMEOUT
    a_time_ms       BIGINT,
    b_time_ms       BIGINT,
    a_assisted      BOOLEAN      NOT NULL DEFAULT FALSE,
    b_assisted      BOOLEAN      NOT NULL DEFAULT FALSE,
    a_progress      INTEGER      NOT NULL DEFAULT 0,
    b_progress      INTEGER      NOT NULL DEFAULT 0,
    caro_moves      VARCHAR(2000) NOT NULL DEFAULT '',
    turn_deadline   TIMESTAMP WITH TIME ZONE,
    rated           BOOLEAN      NOT NULL DEFAULT FALSE,
    version         BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX ix_matches_a ON matches (player_a, created_at);
CREATE INDEX ix_matches_b ON matches (player_b, created_at);
CREATE INDEX ix_matches_status ON matches (status);

-- Chat trong phòng đấu (chỉ hai người chơi của phòng).
CREATE TABLE match_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id   UUID         NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    sender_id  UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    text       VARCHAR(300) NOT NULL,
    client_id  VARCHAR(64)  NOT NULL,
    sent_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_match_msg_client UNIQUE (sender_id, client_id)
);
CREATE INDEX ix_match_msg ON match_messages (match_id, id);

-- Điểm xếp hạng online (Elo đơn giản) theo từng game; chỉ trận không trợ giúp mới tính.
CREATE TABLE user_ratings (
    user_id   UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    game      VARCHAR(16) NOT NULL,
    rating    INTEGER     NOT NULL,
    played    INTEGER     NOT NULL,
    wins      INTEGER     NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, game)
);
CREATE INDEX ix_ratings_board ON user_ratings (game, rating);

