-- Game Hub 4 in 1 — lược đồ ban đầu (PostgreSQL; H2 chế độ PostgreSQL cho dev/test).

CREATE TABLE users (
    id             UUID PRIMARY KEY,
    username       VARCHAR(20)  NOT NULL,
    username_key   VARCHAR(20)  NOT NULL,
    display_name   VARCHAR(30)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    avatar_color   INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_username_key UNIQUE (username_key)
);

-- Refresh token: chỉ lưu SHA-256 của token, xoay vòng theo "họ" (family) để phát hiện dùng lại.
CREATE TABLE refresh_tokens (
    id           UUID PRIMARY KEY,
    user_id      UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id    UUID        NOT NULL,
    token_hash   VARCHAR(64) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_refresh_family ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_user ON refresh_tokens (user_id);

-- Kết quả ván chơi. Điểm (score) do SERVER tính lại; client_id là khoá idempotent theo người dùng.
CREATE TABLE game_results (
    id           UUID PRIMARY KEY,
    user_id      UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    client_id    VARCHAR(64) NOT NULL,
    game         VARCHAR(16) NOT NULL,
    mode         VARCHAR(32) NOT NULL,
    outcome      VARCHAR(8)  NOT NULL,
    score        INTEGER     NOT NULL,
    duration_ms  BIGINT      NOT NULL,
    moves        INTEGER     NOT NULL,
    errors       INTEGER     NOT NULL,
    hints        INTEGER     NOT NULL,
    assisted     BOOLEAN     NOT NULL,
    rankable     BOOLEAN     NOT NULL,
    played_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    details      VARCHAR(16000) NOT NULL,
    CONSTRAINT uq_results_user_client UNIQUE (user_id, client_id)
);
CREATE INDEX ix_results_board ON game_results (game, rankable, played_at);
CREATE INDEX ix_results_user_received ON game_results (user_id, received_at);

-- Thử thách Rubik: hai người giải CÙNG một chuỗi xáo trộn do server sinh.
CREATE TABLE challenges (
    id                     UUID PRIMARY KEY,
    creator_id             UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    opponent_id            UUID        REFERENCES users (id) ON DELETE CASCADE,
    scramble               VARCHAR(200) NOT NULL,
    status                 VARCHAR(12) NOT NULL,
    allow_assist           BOOLEAN     NOT NULL,
    message                VARCHAR(140),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    accepted_at            TIMESTAMP WITH TIME ZONE,
    completed_at           TIMESTAMP WITH TIME ZONE,
    winner_id              UUID,
    creator_client_id      VARCHAR(64),
    creator_duration_ms    BIGINT,
    creator_moves          INTEGER,
    creator_assisted       BOOLEAN,
    creator_solution       VARCHAR(8000),
    creator_submitted_at   TIMESTAMP WITH TIME ZONE,
    opponent_client_id     VARCHAR(64),
    opponent_duration_ms   BIGINT,
    opponent_moves         INTEGER,
    opponent_assisted      BOOLEAN,
    opponent_solution      VARCHAR(8000),
    opponent_submitted_at  TIMESTAMP WITH TIME ZONE,
    version                BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX ix_challenges_creator ON challenges (creator_id, created_at);
CREATE INDEX ix_challenges_opponent ON challenges (opponent_id, created_at);
CREATE INDEX ix_challenges_open ON challenges (status, created_at);

CREATE TABLE chat_messages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id     UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    recipient_id  UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    text          VARCHAR(500) NOT NULL,
    client_id     VARCHAR(64)  NOT NULL,
    sent_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_chat_sender_client UNIQUE (sender_id, client_id)
);
CREATE INDEX ix_chat_pair ON chat_messages (sender_id, recipient_id, id);
CREATE INDEX ix_chat_recipient ON chat_messages (recipient_id, id);

CREATE TABLE user_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id  UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id  UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_block_pair UNIQUE (blocker_id, blocked_id)
);

CREATE TABLE reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id  UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reported_id  UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    message_id   BIGINT,
    reason       VARCHAR(500) NOT NULL,
    status       VARCHAR(12)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Vị trí gần đúng: chỉ lưu ô lưới đã làm tròn 0,01° (~1,1 km), không lưu toạ độ gốc.
CREATE TABLE presence (
    user_id     UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    cell_lat    DOUBLE PRECISION NOT NULL,
    cell_lon    DOUBLE PRECISION NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_presence_expires ON presence (expires_at);
